  id INTEGER PRIMARY KEY AUTOINCREMENT,
  site_name TEXT NOT NULL,
  content TEXT DEFAULT '',             -- 처리해야 할 내용
  due_date TEXT,                       -- 예정일 YYYY-MM-DD (선택)
