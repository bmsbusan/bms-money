  id INTEGER PRIMARY KEY AUTOINCREMENT,
  work_date TEXT NOT NULL,             -- 작업 날짜 YYYY-MM-DD
  site_name TEXT NOT NULL,
  content TEXT DEFAULT '',             -- 작업내역
