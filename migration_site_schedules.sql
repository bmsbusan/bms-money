CREATE TABLE IF NOT EXISTS site_schedules (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  site_name TEXT NOT NULL,
  category TEXT DEFAULT '',            -- 구분 (예: 승강기안전검사, 건물화재보험 등)
  remarks TEXT DEFAULT '',             -- 비고 (업체명 등)
  due_date TEXT,                       -- 만기 도래일 YYYY-MM-DD (직접 입력/수정 가능, 해당없음이면 NULL)
  amount TEXT DEFAULT '',              -- 금액 (숫자와 '부과 예정' 같은 텍스트가 섞여 있어 문자열로 보관)
  fee_note TEXT DEFAULT '',            -- 관리비 적용 (개월수 또는 텍스트 메모)
  tag TEXT NOT NULL DEFAULT '기타',    -- 보험 / 건물 점검 / 설비 점검 / 소독 / 저수조청소 / 기타
  created_at TEXT NOT NULL DEFAULT (datetime('now')),
  updated_at TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE INDEX IF NOT EXISTS idx_site_schedules_due ON site_schedules(due_date);
CREATE INDEX IF NOT EXISTS idx_site_schedules_site ON site_schedules(site_name);
CREATE INDEX IF NOT EXISTS idx_site_schedules_tag ON site_schedules(tag);


